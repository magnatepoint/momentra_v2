#!/usr/bin/env node
// Momentra design-token + taxonomy generator (Personal v1.1).
//
//   node generate-tokens.mjs           regenerate every output (idempotent; only changed files are written)
//   node generate-tokens.mjs --check   verify outputs are up to date (exit 1 if not); use in CI
//
// Inputs (single source of truth):
//   design/tokens/personal.tokens.json        colors, radii, spacing, sizes, shadow, typography
//   design/taxonomy/personal-taxonomy.v1.json 8 life areas, 48 subcategories, 5 moods
//
// Outputs:
//   iOS      momentra/momentra/Design/Generated/PersonalTokens.generated.swift
//            momentra/momentra/Design/Generated/PersonalLifeTaxonomy.generated.swift
//            momentra/momentra/Assets.xcassets/PersonalTokens/*.colorset
//   Android  apk/app/src/main/java/com/example/momentra/ui/theme/generated/PersonalTokens.kt
//            apk/app/src/main/java/com/example/momentra/ui/theme/generated/PersonalLifeTaxonomy.kt
//   Backend  backend/typescript/src/modules/personal/taxonomy.generated.ts
//            frds/seeds/personal/personal_life_taxonomy.v1.seed.sql   (seed only; NOT a migration)
//
// Icons referenced by the catalogs (PersonalIcons/<key>, R.drawable.ic_pers_<key>) are produced by
// import-assets.mjs; run both (`npm run all`).
import path from 'node:path';
import { PATHS, Plan, readJson, camel, pascal, snake, parseColor, argbHex, rgbHex, fmt } from './lib.mjs';

const check = process.argv.includes('--check');
const tokens = readJson(PATHS.tokens);
const taxonomy = readJson(PATHS.taxonomy);
const plan = new Plan({ check });

const SRC_TOKENS = 'design/tokens/personal.tokens.json';
const SRC_TAX = 'design/taxonomy/personal-taxonomy.v1.json';
const banner = (c, src) => `${c} GENERATED by tools/design-pipeline/generate-tokens.mjs from ${src}.\n${c} DO NOT EDIT by hand: change the source JSON and run \`npm run tokens\` in tools/design-pipeline.\n`;

// ---------------------------------------------------------------- token model
function flatten(node, prefix = [], out = []) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$')) continue;
    if (v && typeof v === 'object' && '$value' in v) out.push({ path: [...prefix, k], type: v.$type, raw: v.$value, ext: v.$extensions });
    else if (v && typeof v === 'object') flatten(v, [...prefix, k], out);
  }
  return out;
}
const all = flatten(tokens);
const byPath = new Map(all.map((t) => [t.path.join('.'), t]));
function resolve(value, seen = []) {
  if (typeof value === 'string') {
    const m = /^\{([^}]+)\}$/.exec(value);
    if (m) {
      if (seen.includes(m[1])) throw new Error(`Alias cycle: ${[...seen, m[1]].join(' -> ')}`);
      const t = byPath.get(m[1]);
      if (!t) throw new Error(`Unknown alias {${m[1]}}`);
      return resolve(t.raw, [...seen, m[1]]);
    }
  }
  return value;
}
for (const t of all) { t.value = resolve(t.raw); t.alias = typeof t.raw === 'string' && t.raw.startsWith('{') ? t.raw.slice(1, -1) : null; }
const group = (g) => all.filter((t) => t.path[0] === g);

const colors = group('color').map((t) => {
  const sub = t.path.slice(1);
  return { ...t, sub, c: parseColor(t.value), swift: camel(sub), kt: pascal(sub), colorset: pascal(sub), note: t.alias ? `= ${t.alias}` : (t.ext?.figma ?? '') };
});
const dims = (g) => group(g).map((t) => ({ ...t, swift: camel(t.path.slice(1)), kt: pascal(t.path.slice(1)) }));
const radius = dims('radius'), space = dims('space'), size = dims('size');
const shadows = group('shadow').map((t) => ({ ...t, swift: camel(t.path.slice(1)), kt: pascal(t.path.slice(1)), c: parseColor(t.value.color) }));
const faces = Object.fromEntries(group('font').filter((t) => t.path[1] === 'face').map((t) => [Number(t.path[2]), t.value]));
const type = group('typography').map((t) => {
  const v = t.value;
  const face = faces[v.fontWeight];
  if (!face) throw new Error(`No font face for weight ${v.fontWeight} (${t.path.join('.')})`);
  return { ...t, v, face, swift: camel(t.path.slice(1)), kt: pascal(t.path.slice(1)) };
});
const colorByPath = new Map(colors.map((c) => [['color', ...c.sub].join('.'), c]));
const tintOf = (tokenPath) => { const c = colorByPath.get(tokenPath); if (!c) throw new Error(`Unknown tint token ${tokenPath}`); return c; };

// ---------------------------------------------------------------- taxonomy validation
const areas = [...taxonomy.areas].sort((a, b) => a.sortOrder - b.sortOrder);
const subs = [...taxonomy.subcategories].sort((a, b) => a.area.localeCompare(b.area) || a.sortOrder - b.sortOrder);
const moods = [...taxonomy.moods].sort((a, b) => a.sortOrder - b.sortOrder);
{
  const errs = [];
  if (areas.length !== 8) errs.push(`expected 8 areas, got ${areas.length}`);
  if (subs.length !== 48) errs.push(`expected 48 subcategories, got ${subs.length}`);
  if (moods.length !== 5) errs.push(`expected 5 moods, got ${moods.length}`);
  const codes = new Set();
  for (const a of areas) {
    if (!/^P[1-8]$/.test(a.code)) errs.push(`bad area code ${a.code}`);
    if (!['NOW', 'BUILD'].includes(a.layer)) errs.push(`bad layer ${a.layer} on ${a.code}`);
    tintOf(a.tint);
    if (subs.filter((s) => s.area === a.code).length !== 6) errs.push(`${a.code} must have exactly 6 subcategories`);
  }
  for (const s of subs) {
    if (codes.has(s.code)) errs.push(`duplicate ${s.code}`);
    codes.add(s.code);
    if (!s.code.startsWith(`${s.area}.`)) errs.push(`${s.code} is not a child of ${s.area}`);
    if (!/^[a-z0-9-]+$/.test(s.icon)) errs.push(`bad icon key ${s.icon}`);
  }
  if (errs.length) { console.error('Taxonomy invalid:\n  ' + errs.join('\n  ')); process.exit(2); }
}
const areaByCode = new Map(areas.map((a) => [a.code, a]));

// ---------------------------------------------------------------- string escaping
const swiftStr = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const ktStr = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const tsStr = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const sqlStr = (s) => `'${String(s).replace(/'/g, "''")}'`;
const cg = (n) => { const s = fmt(n, 3); return s.includes('.') ? s : `${s}`; };
const ktFloat = (n) => { const s = fmt(n, 3); return s.includes('.') ? s : `${s}`; };

// ---------------------------------------------------------------- iOS colorsets
const colorsetDir = path.join(PATHS.iosAssets, 'PersonalTokens');
plan.own(colorsetDir, () => true);
plan.json(path.join(colorsetDir, 'Contents.json'), { info: { author: 'xcode', version: 1 }, properties: { 'provides-namespace': true } });
for (const c of colors) {
  const comp = { 'color-space': 'srgb', components: { alpha: c.c.a.toFixed(3), blue: `0x${c.c.b.toString(16).toUpperCase().padStart(2, '0')}`, green: `0x${c.c.g.toString(16).toUpperCase().padStart(2, '0')}`, red: `0x${c.c.r.toString(16).toUpperCase().padStart(2, '0')}` } };
  plan.json(path.join(colorsetDir, `${c.colorset}.colorset`, 'Contents.json'), {
    colors: [
      { color: comp, idiom: 'universal' },
      { appearances: [{ appearance: 'luminosity', value: 'dark' }], color: comp, idiom: 'universal' },
    ],
    info: { author: 'xcode', version: 1 },
  });
}

// ---------------------------------------------------------------- iOS Swift tokens
{
  const L = [];
  L.push(banner('//', SRC_TOKENS));
  L.push('// Personal v1.1 design tokens. PERSONAL MODE ONLY: Group, Business and Circle keep their themes.');
  L.push('// Colors resolve from Assets.xcassets/PersonalTokens/*.colorset (dark == light until a light theme exists).');
  L.push('// Do NOT assign any of these to the global AccentColor.');
  L.push('');
  L.push('import SwiftUI');
  L.push('import UIKit');
  L.push('');
  L.push('enum PersonalTokens {');
  L.push('    enum Colors {');
  for (const c of colors) L.push(`        /// ${rgbHex(c.c)}${c.c.a < 1 ? ` @ ${fmt(c.c.a, 2)}` : ''}${c.note ? ` (${c.note})` : ''}`, `        static let ${c.swift} = Color("PersonalTokens/${c.colorset}", bundle: .main)`);
  L.push('');
  L.push('        /// Life-area tint by area code ("P1"..."P8").');
  L.push('        static func area(_ code: String) -> Color {');
  L.push('            switch code {');
  for (const a of areas) L.push(`            case ${swiftStr(a.code)}: return ${tintOf(a.tint).swift}`);
  L.push('            default: return brandPrimary');
  L.push('            }');
  L.push('        }');
  L.push('    }');
  for (const [name, list] of [['Radius', radius], ['Space', space], ['Size', size]]) {
    L.push('', `    enum ${name} {`);
    for (const d of list) L.push(`        static let ${d.swift}: CGFloat = ${cg(d.value)}`);
    L.push('    }');
  }
  L.push('', '    struct ShadowStyle: Hashable {', '        let color: Color', '        let radius: CGFloat', '        let x: CGFloat', '        let y: CGFloat', '    }', '', '    enum Shadow {');
  for (const s of shadows) L.push(`        /// Figma blur ${s.value.blur} -> SwiftUI radius ${cg(s.value.blur / 2)}`, `        static let ${s.swift} = ShadowStyle(color: Color(.sRGB, red: ${cg(s.c.r / 255)}, green: ${cg(s.c.g / 255)}, blue: ${cg(s.c.b / 255)}, opacity: ${cg(s.value.alpha)}), radius: ${cg(s.value.blur / 2)}, x: ${cg(s.value.offsetX)}, y: ${cg(s.value.offsetY)})`);
  L.push('    }');
  L.push('', '    enum FontName {');
  for (const [w, f] of Object.entries(faces)) L.push(`        static let w${w} = ${swiftStr(f.postScriptName)}`);
  L.push('    }');
  L.push('', '    enum Typography {');
  for (const t of type) L.push(`        static let ${t.swift} = PersonalTextStyle(postScriptName: ${swiftStr(t.face.postScriptName)}, size: ${cg(t.v.fontSize)}, lineHeight: ${cg(t.v.lineHeight)}, tracking: ${cg(t.v.letterSpacing)}, uppercase: ${t.v.textCase === 'uppercase'}, relativeTo: .${t.v.iosRelativeTo})`);
  L.push('    }');
  L.push('}');
  L.push('');
  L.push('/// A Plus Jakarta Sans text style that scales with Dynamic Type.');
  L.push('struct PersonalTextStyle: Hashable {');
  L.push('    let postScriptName: String');
  L.push('    let size: CGFloat');
  L.push('    let lineHeight: CGFloat');
  L.push('    let tracking: CGFloat');
  L.push('    let uppercase: Bool');
  L.push('    let relativeTo: Font.TextStyle');
  L.push('');
  L.push('    var font: Font { Font.custom(postScriptName, size: size, relativeTo: relativeTo) }');
  L.push('');
  L.push('    var uiFont: UIFont {');
  L.push('        let base = UIFont(name: postScriptName, size: size) ?? UIFont.systemFont(ofSize: size)');
  L.push('        return UIFontMetrics(forTextStyle: relativeTo.personalUIKitStyle).scaledFont(for: base)');
  L.push('    }');
  L.push('');
  L.push('    /// Extra spacing between lines so the rendered line height matches the token.');
  L.push('    var lineSpacing: CGFloat {');
  L.push('        let scale = UIFontMetrics(forTextStyle: relativeTo.personalUIKitStyle).scaledValue(for: lineHeight) / max(lineHeight, 1)');
  L.push('        return max(0, lineHeight * scale - uiFont.lineHeight)');
  L.push('    }');
  L.push('}');
  L.push('');
  L.push('private extension Font.TextStyle {');
  L.push('    var personalUIKitStyle: UIFont.TextStyle {');
  L.push('        switch self {');
  L.push('        case .largeTitle: return .largeTitle');
  L.push('        case .title: return .title1');
  L.push('        case .title2: return .title2');
  L.push('        case .title3: return .title3');
  L.push('        case .headline: return .headline');
  L.push('        case .subheadline: return .subheadline');
  L.push('        case .callout: return .callout');
  L.push('        case .footnote: return .footnote');
  L.push('        case .caption: return .caption1');
  L.push('        case .caption2: return .caption2');
  L.push('        default: return .body');
  L.push('        }');
  L.push('    }');
  L.push('}');
  L.push('');
  L.push('private struct PersonalTextModifier: ViewModifier {');
  L.push('    let style: PersonalTextStyle');
  L.push('');
  L.push('    func body(content: Content) -> some View {');
  L.push('        content');
  L.push('            .font(style.font)');
  L.push('            .tracking(style.tracking)');
  L.push('            .lineSpacing(style.lineSpacing)');
  L.push('            .textCase(style.uppercase ? .uppercase : nil)');
  L.push('    }');
  L.push('}');
  L.push('');
  L.push('extension View {');
  L.push('    /// Applies a Personal v1.1 type style: `Text("Pulse").personalText(PersonalTokens.Typography.section)`.');
  L.push('    func personalText(_ style: PersonalTextStyle) -> some View {');
  L.push('        modifier(PersonalTextModifier(style: style))');
  L.push('    }');
  L.push('}');
  plan.text(path.join(PATHS.iosGenerated, 'PersonalTokens.generated.swift'), L.join('\n') + '\n');
}

// ---------------------------------------------------------------- iOS Swift taxonomy
{
  const L = [];
  L.push(banner('//', SRC_TAX));
  L.push('// Personal v1.1 context taxonomy: 8 life areas (P1-P8), 48 subcategories (P1.1-P8.6), 5 moods.');
  L.push('// Icons: Assets.xcassets/PersonalIcons/<iconKey> (template SVG). Tints: PersonalTokens.Colors.');
  L.push('');
  L.push('import SwiftUI');
  L.push('');
  L.push('enum PersonalLifeLayer: String, CaseIterable, Hashable {');
  for (const l of taxonomy.layers) L.push(`    case ${l.code.toLowerCase()} = ${swiftStr(l.code)}`);
  L.push('', '    var label: String {', '        switch self {');
  for (const l of taxonomy.layers) L.push(`        case .${l.code.toLowerCase()}: return ${swiftStr(l.label)}`);
  L.push('        }', '    }', '}', '');
  L.push('struct PersonalLifeArea: Identifiable, Hashable {');
  L.push('    let code: String', '    let layer: PersonalLifeLayer', '    let label: String', '    let tagline: String', '    let iconKey: String', '    let sortOrder: Int', '');
  L.push('    var id: String { code }');
  L.push('    var iconAssetName: String { "PersonalIcons/" + iconKey }');
  L.push('    var icon: Image { Image(iconAssetName).renderingMode(.template) }');
  L.push('    var tint: Color { PersonalTokens.Colors.area(code) }');
  L.push('    var subcategories: [PersonalLifeSubcategory] { PersonalLifeTaxonomy.subcategories(in: code) }');
  L.push('}', '');
  L.push('struct PersonalLifeSubcategory: Identifiable, Hashable {');
  L.push('    let code: String', '    let areaCode: String', '    let label: String', '    let detail: String', '    let examples: [String]', '    let iconKey: String', '    let sortOrder: Int', '');
  L.push('    var id: String { code }');
  L.push('    var iconAssetName: String { "PersonalIcons/" + iconKey }');
  L.push('    var icon: Image { Image(iconAssetName).renderingMode(.template) }');
  L.push('    /// L3 glyphs take their parent area tint.');
  L.push('    var tint: Color { PersonalTokens.Colors.area(areaCode) }');
  L.push('    var area: PersonalLifeArea? { PersonalLifeTaxonomy.area(areaCode) }');
  L.push('}', '');
  L.push('/// Optional, user-chosen, never inferred. No mood is not the same as `.okay`.');
  L.push('enum PersonalMood: String, CaseIterable, Identifiable, Hashable {');
  for (const m of moods) L.push(`    case ${m.code.toLowerCase()} = ${swiftStr(m.code)}`);
  L.push('', '    var id: String { rawValue }', '', '    var label: String {', '        switch self {');
  for (const m of moods) L.push(`        case .${m.code.toLowerCase()}: return ${swiftStr(m.label)}`);
  L.push('        }', '    }', '', '    var iconKey: String {', '        switch self {');
  for (const m of moods) L.push(`        case .${m.code.toLowerCase()}: return ${swiftStr(m.icon)}`);
  L.push('        }', '    }', '', '    var iconAssetName: String { "PersonalIcons/" + iconKey }', '    var icon: Image { Image(iconAssetName).renderingMode(.template) }', '}', '');
  L.push('enum PersonalLifeTaxonomy {');
  L.push(`    static let version = ${taxonomy.version}`, '');
  L.push('    static let areas: [PersonalLifeArea] = [');
  for (const a of areas) L.push(`        PersonalLifeArea(code: ${swiftStr(a.code)}, layer: .${a.layer.toLowerCase()}, label: ${swiftStr(a.label)}, tagline: ${swiftStr(a.tagline)}, iconKey: ${swiftStr(a.icon)}, sortOrder: ${a.sortOrder}),`);
  L.push('    ]', '');
  L.push('    static let subcategories: [PersonalLifeSubcategory] = [');
  for (const s of subs) L.push(`        PersonalLifeSubcategory(code: ${swiftStr(s.code)}, areaCode: ${swiftStr(s.area)}, label: ${swiftStr(s.label)}, detail: ${swiftStr(s.description)}, examples: [${s.examples.map(swiftStr).join(', ')}], iconKey: ${swiftStr(s.icon)}, sortOrder: ${s.sortOrder}),`);
  L.push('    ]', '');
  L.push('    private static let areaIndex: [String: PersonalLifeArea] = Dictionary(uniqueKeysWithValues: areas.map { ($0.code, $0) })');
  L.push('    private static let subcategoryIndex: [String: PersonalLifeSubcategory] = Dictionary(uniqueKeysWithValues: subcategories.map { ($0.code, $0) })', '');
  L.push('    static func area(_ code: String) -> PersonalLifeArea? { areaIndex[code] }');
  L.push('    static func subcategory(_ code: String) -> PersonalLifeSubcategory? { subcategoryIndex[code] }');
  L.push('    static func subcategories(in areaCode: String) -> [PersonalLifeSubcategory] { subcategories.filter { $0.areaCode == areaCode } }');
  L.push('    static func areas(in layer: PersonalLifeLayer) -> [PersonalLifeArea] { areas.filter { $0.layer == layer } }', '');
  L.push('    /// Exactly one area and one subcategory of that area; cross-parent pairs are rejected.');
  L.push('    static func isValid(areaCode: String, subcategoryCode: String) -> Bool {');
  L.push('        subcategoryIndex[subcategoryCode]?.areaCode == areaCode');
  L.push('    }');
  L.push('}');
  plan.text(path.join(PATHS.iosGenerated, 'PersonalLifeTaxonomy.generated.swift'), L.join('\n') + '\n');
}

